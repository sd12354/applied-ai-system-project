"""
Reliability harness for the VibeFinder Agent.

Runs a fixed suite of requests through the agent and grades each one
against an expectation, then writes a parseable report (Markdown table +
JSON) to the assets/ folder. This is the "prove it works, don't just
claim it" part of the project.

Run it with:
    python -m src.evaluate

It prints a summary and writes:
    assets/evaluation_report.md
    assets/evaluation_report.json
"""

import json
import os
from dataclasses import dataclass
from typing import Optional, List

from src.agent import RecommenderAgent


@dataclass
class Case:
    query: str
    expect_genre: Optional[str] = None   # top pick should be this genre
    expect_graceful: bool = False        # vague input: should be handled, not matched


# The evaluation suite: ordinary requests plus deliberate edge cases.
CASES: List[Case] = [
    Case("upbeat pop for a workout", expect_genre="pop"),
    Case("chill lofi for studying", expect_genre="lofi"),
    Case("intense rock music", expect_genre="rock"),
    Case("romantic r&b", expect_genre="r&b"),
    Case("acoustic country roadtrip", expect_genre="country"),
    Case("some jazz", expect_genre="jazz"),            # should pass only after a retry
    Case("", expect_graceful=True),                    # empty input guardrail
    Case("qwerty blah blah", expect_graceful=True),    # unrecognized input guardrail
]

REPORT_MD = os.path.join("assets", "evaluation_report.md")
REPORT_JSON = os.path.join("assets", "evaluation_report.json")


def grade(case: Case, result) -> bool:
    """Decide whether the agent handled this case correctly."""
    if not result.recommendations:
        return False  # never acceptable to return nothing
    if case.expect_graceful:
        # Correct behavior is to flag low confidence and attach an advisory
        # rather than pretend it nailed a vague request.
        return (not result.passed) and (result.advisory is not None)
    top_genre = result.recommendations[0][0]["genre"]
    return result.passed and top_genre == case.expect_genre


def run_suite():
    agent = RecommenderAgent()
    rows = []
    for case in CASES:
        result = agent.run(case.query)
        ok = grade(case, result)
        rows.append({
            "query": case.query or "(empty)",
            "expected": (f"top genre = {case.expect_genre}"
                         if not case.expect_graceful else "handled gracefully"),
            "top_pick": result.recommendations[0][0]["title"],
            "top_genre": result.recommendations[0][0]["genre"],
            "confidence": result.confidence,
            "attempts": result.attempts,
            "passed_checks": result.passed,
            "result": "PASS" if ok else "FAIL",
        })
    return rows


def summarize(rows):
    total = len(rows)
    passed = sum(1 for r in rows if r["result"] == "PASS")
    retried = sum(1 for r in rows if r["attempts"] > 1)
    confident = [r["confidence"] for r in rows if not r["query"] == "(empty)"]
    avg_conf = round(sum(confident) / len(confident), 2) if confident else 0.0
    return {
        "total": total,
        "passed": passed,
        "failed": total - passed,
        "pass_rate": round(passed / total, 2) if total else 0.0,
        "self_corrected_via_retry": retried,
        "avg_confidence_excluding_empty": avg_conf,
    }


def write_reports(rows, summary):
    os.makedirs("assets", exist_ok=True)

    lines = [
        "# VibeFinder Agent — Reliability Report",
        "",
        "Generated by `python -m src.evaluate`. Each request is parsed, "
        "answered, and self-checked by the agent; the result is graded "
        "against the expectation.",
        "",
        f"- **Cases:** {summary['total']}",
        f"- **Passed:** {summary['passed']} / {summary['total']} "
        f"(pass rate {summary['pass_rate']:.0%})",
        f"- **Self-corrected via a retry:** {summary['self_corrected_via_retry']}",
        f"- **Average confidence (excluding empty input):** "
        f"{summary['avg_confidence_excluding_empty']:.2f}",
        "",
        "| Request | Expected | Top pick | Genre | Confidence | Attempts | Checks | Result |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        lines.append(
            f"| {r['query']} | {r['expected']} | {r['top_pick']} | {r['top_genre']} "
            f"| {r['confidence']:.2f} | {r['attempts']} | "
            f"{'ok' if r['passed_checks'] else 'low'} | {r['result']} |"
        )
    lines.append("")
    with open(REPORT_MD, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    with open(REPORT_JSON, "w", encoding="utf-8") as f:
        json.dump({"summary": summary, "cases": rows}, f, indent=2)


def main():
    rows = run_suite()
    summary = summarize(rows)
    write_reports(rows, summary)
    print(f"Ran {summary['total']} cases: {summary['passed']} passed, "
          f"{summary['failed']} failed (pass rate {summary['pass_rate']:.0%}).")
    print(f"Self-corrected via a retry: {summary['self_corrected_via_retry']}. "
          f"Avg confidence (non-empty): {summary['avg_confidence_excluding_empty']:.2f}.")
    print(f"Wrote {REPORT_MD} and {REPORT_JSON}.")
    # Non-zero exit if anything failed, so CI / graders can tell at a glance.
    return 0 if summary["failed"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
